-- Team Recruitment Automation Tool
-- Migration 001: Supabase PostgreSQL Schema (Sushmita's Canonical DDL)
-- Covers campaigns, datasets, teams, members, criteria, member_signals, configs,
-- runs, run_results, run_score_details, run_rule_results, data_flags, overrides,
-- pairwise_comparisons, and audit_log.

CREATE TABLE IF NOT EXISTS public.campaigns (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_id UUID NOT NULL REFERENCES auth.users(id),
    name TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.datasets (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id INTEGER REFERENCES public.campaigns(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    source_format TEXT NOT NULL CHECK (source_format IN ('csv', 'json')),
    file_hash TEXT,
    column_mapping JSONB NOT NULL DEFAULT '{}'::jsonb,
    total_teams INTEGER NOT NULL DEFAULT 0,
    uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.teams (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id INTEGER NOT NULL REFERENCES public.datasets(id) ON DELETE CASCADE,
    external_id TEXT NOT NULL,
    team_name TEXT NOT NULL,
    team_size INTEGER NOT NULL DEFAULT 0,
    extra_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    UNIQUE (dataset_id, external_id)
);

CREATE TABLE IF NOT EXISTS public.members (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    full_name TEXT NOT NULL,
    email TEXT,
    gender CHAR,
    resume_url TEXT,
    github_url TEXT,
    linkedin_url TEXT,
    portfolio_url TEXT,
    resume_text TEXT
);

CREATE TABLE IF NOT EXISTS public.criteria (
    key TEXT PRIMARY KEY,
    label TEXT NOT NULL,
    source TEXT NOT NULL,
    value_type TEXT NOT NULL CHECK (value_type IN ('number', 'boolean', 'text')),
    description TEXT
);

CREATE TABLE IF NOT EXISTS public.member_signals (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id INTEGER NOT NULL REFERENCES public.members(id) ON DELETE CASCADE,
    criterion_key TEXT NOT NULL REFERENCES public.criteria(key),
    value_num DOUBLE PRECISION,
    value_text TEXT,
    status TEXT NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'missing', 'fetch_failed', 'low_confidence')),
    confidence REAL CHECK (confidence IS NULL OR confidence BETWEEN 0 AND 1),
    evidence TEXT,
    extractor_version TEXT,
    fetched_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.configs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    config_json JSONB NOT NULL DEFAULT '{}'::jsonb,
    config_hash TEXT,
    is_preset BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dataset_id INTEGER NOT NULL REFERENCES public.datasets(id),
    config_id INTEGER NOT NULL REFERENCES public.configs(id),
    config_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    top_x INTEGER NOT NULL CHECK (top_x > 0),
    teams_total INTEGER NOT NULL DEFAULT 0,
    teams_shortlisted INTEGER NOT NULL DEFAULT 0,
    result_hash TEXT,
    run_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.run_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
    team_id INTEGER NOT NULL REFERENCES public.teams(id),
    is_eligible BOOLEAN NOT NULL DEFAULT TRUE,
    total_score REAL,
    rank INTEGER,
    outcome TEXT NOT NULL CHECK (outcome IN ('shortlisted', 'waitlisted', 'rejected', 'ineligible', 'excluded')),
    reason TEXT,
    has_missing_data BOOLEAN NOT NULL DEFAULT FALSE,
    tie_break_note TEXT,
    UNIQUE (run_id, team_id)
);

CREATE TABLE IF NOT EXISTS public.run_score_details (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
    team_id INTEGER NOT NULL REFERENCES public.teams(id),
    criterion_key TEXT NOT NULL REFERENCES public.criteria(key),
    team_raw_value TEXT,
    normalized_value REAL,
    weight REAL NOT NULL DEFAULT 0,
    weighted_score REAL,
    data_status TEXT NOT NULL DEFAULT 'ok' CHECK (data_status IN ('ok', 'partial', 'missing')),
    members_with_data INTEGER NOT NULL DEFAULT 0,
    members_total INTEGER NOT NULL DEFAULT 0,
    explanation TEXT
);

CREATE TABLE IF NOT EXISTS public.run_rule_results (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
    team_id INTEGER NOT NULL REFERENCES public.teams(id),
    rule_name TEXT NOT NULL,
    passed BOOLEAN NOT NULL,
    details TEXT
);

CREATE TABLE IF NOT EXISTS public.data_flags (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    team_id INTEGER NOT NULL REFERENCES public.teams(id) ON DELETE CASCADE,
    member_id INTEGER REFERENCES public.members(id) ON DELETE SET NULL,
    flag_type TEXT NOT NULL,
    severity TEXT NOT NULL CHECK (severity IN ('info', 'warning', 'severe')),
    details TEXT
);

CREATE TABLE IF NOT EXISTS public.overrides (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
    team_id INTEGER NOT NULL REFERENCES public.teams(id),
    action TEXT NOT NULL CHECK (action IN ('pin', 'exclude', 'waitlist')),
    reason TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID REFERENCES auth.users(id)
);

CREATE TABLE IF NOT EXISTS public.pairwise_comparisons (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES public.runs(id) ON DELETE CASCADE,
    team_a_id INTEGER NOT NULL REFERENCES public.teams(id),
    team_b_id INTEGER NOT NULL REFERENCES public.teams(id),
    preferred_team_id INTEGER REFERENCES public.teams(id),
    reason TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by UUID REFERENCES auth.users(id),
    CHECK (team_a_id <> team_b_id),
    CHECK (preferred_team_id IS NULL OR preferred_team_id IN (team_a_id, team_b_id))
);

CREATE TABLE IF NOT EXISTS public.audit_log (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    table_name TEXT NOT NULL,
    record_id INTEGER,
    action TEXT NOT NULL CHECK (action IN ('insert', 'update', 'delete')),
    old_values JSONB,
    new_values JSONB,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    changed_by UUID REFERENCES auth.users(id)
);

-- Indexes
CREATE INDEX IF NOT EXISTS idx_campaigns_owner_id ON public.campaigns(owner_id);
CREATE INDEX IF NOT EXISTS idx_datasets_campaign_id ON public.datasets(campaign_id);
CREATE INDEX IF NOT EXISTS idx_teams_dataset ON public.teams(dataset_id);
CREATE INDEX IF NOT EXISTS idx_members_team ON public.members(team_id);
CREATE INDEX IF NOT EXISTS idx_signals_member ON public.member_signals(member_id);
CREATE INDEX IF NOT EXISTS idx_signals_criterion ON public.member_signals(criterion_key);
CREATE INDEX IF NOT EXISTS idx_runs_dataset ON public.runs(dataset_id);
CREATE INDEX IF NOT EXISTS idx_runs_config ON public.runs(config_id);
CREATE INDEX IF NOT EXISTS idx_results_run ON public.run_results(run_id);
CREATE INDEX IF NOT EXISTS idx_results_team ON public.run_results(team_id);
CREATE INDEX IF NOT EXISTS idx_score_details_run_team ON public.run_score_details(run_id, team_id);
CREATE INDEX IF NOT EXISTS idx_rule_results_run_team ON public.run_rule_results(run_id, team_id);
CREATE INDEX IF NOT EXISTS idx_flags_team ON public.data_flags(team_id);
CREATE INDEX IF NOT EXISTS idx_overrides_run_team ON public.overrides(run_id, team_id);
CREATE INDEX IF NOT EXISTS idx_audit_changed_at ON public.audit_log(changed_at);
